from concurrent.futures import ThreadPoolExecutor
from datetime import date
from pathlib import Path
import re
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "Bing.Utils.DateTime" / "Bing" / "Date" / "Chinese" / "ChineseSolarTermDateData.cs"
MIN_YEAR = 1900
MAX_YEAR = 2100
TERMS_PER_YEAR = 24
HKO_URL = "https://www.hko.gov.hk/en/gts/time/calendar/text/files/T{year}e.txt"

TERM_NAMES = (
    "Moderate Cold",
    "Severe Cold",
    "Spring Commences",
    "Spring Showers",
    "Insects Waken",
    "Vernal Equinox",
    "Bright & Clear",
    "Corn Rain",
    "Summer Commences",
    "Corn Forms",
    "Corn on Ear",
    "Summer Solstice",
    "Moderate Heat",
    "Great Heat",
    "Autumn Commences",
    "End of Heat",
    "White Dew",
    "Autumnal Equinox",
    "Cold Dew",
    "Frost",
    "Winter Commences",
    "Light Snow",
    "Heavy Snow",
    "Winter Solstice",
)

# The Purple Mountain Observatory's 1900 calendar gives the solar terms in Beijing time.
DAYS_1900 = (
    6, 20, 4, 19, 6, 21, 5, 20, 6, 21, 6, 22,
    7, 23, 8, 23, 8, 23, 9, 24, 8, 23, 7, 22,
)

DATE_LINE = re.compile(rb"^(\d{4})/(\d{1,2})/(\d{1,2})\s+")


def fetch_and_parse_year(year):
    request = Request(HKO_URL.format(year=year), headers={"User-Agent": "Bing.Utils solar-term data generator"})
    with urlopen(request, timeout=30) as response:
        payload = response.read()

    days = [None] * TERMS_PER_YEAR
    for raw_line in payload.splitlines():
        date_match = DATE_LINE.match(raw_line)
        if date_match is None:
            continue

        # Some old files contain non-UTF-8 material outside their ASCII date rows.
        if not raw_line.isascii():
            raise ValueError(f"Non-ASCII date row in HKO {year} data")
        line = raw_line.decode("utf-8")
        row_year, month, day = map(int, date_match.groups())
        if row_year != year:
            raise ValueError(f"Unexpected year in HKO {year} data: {row_year}")

        term_index = next((index for index, name in enumerate(TERM_NAMES) if line.rstrip().endswith(name)), None)
        if term_index is None:
            continue
        if days[term_index] is not None:
            raise ValueError(f"Duplicate solar term {term_index} in HKO {year} data")

        expected_month = term_index // 2 + 1
        if month != expected_month:
            raise ValueError(f"Unexpected month for HKO {year} term {term_index}: {month}")
        date(year, month, day)
        days[term_index] = day

    missing = [index for index, day in enumerate(days) if day is None]
    if missing:
        raise ValueError(f"HKO {year} data is missing solar terms: {missing}")
    for index in range(0, TERMS_PER_YEAR, 2):
        if days[index] >= days[index + 1]:
            raise ValueError(f"HKO {year} solar-term dates are not in chronological order")
    return tuple(days)


def validate_1900():
    if len(DAYS_1900) != TERMS_PER_YEAR:
        raise ValueError("1900 must contain 24 solar-term dates")
    for index, day in enumerate(DAYS_1900):
        date(MIN_YEAR, index // 2 + 1, day)
    for index in range(0, TERMS_PER_YEAR, 2):
        if DAYS_1900[index] >= DAYS_1900[index + 1]:
            raise ValueError("1900 solar-term dates are not in chronological order")


def render_source(years):
    lines = [
        "// <auto-generated />",
        "namespace Bing.Date.Chinese;",
        "",
        "internal static class ChineseSolarTermDateData",
        "{",
        f"    internal const int MinYear = {MIN_YEAR};",
        f"    internal const int MaxYear = {MAX_YEAR};",
        "    private const int TermsPerYear = 24;",
        "",
        "    private static readonly byte[] DayOfMonthByTerm =",
        "    {",
    ]

    for year, days in years:
        lines.append(f"        // {year}")
        lines.append("        " + ", ".join(map(str, days)) + ",")

    lines.extend(
        [
            "    };",
            "",
            "    internal static bool IsSupportedYear(int year) => year >= MinYear && year <= MaxYear;",
            "",
            "    internal static int GetDayOfMonth(int year, int termIndex) =>",
            "        DayOfMonthByTerm[(year - MinYear) * TermsPerYear + termIndex];",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main():
    validate_1900()
    with ThreadPoolExecutor(max_workers=4) as executor:
        hko_years = list(executor.map(fetch_and_parse_year, range(MIN_YEAR + 1, MAX_YEAR + 1)))

    years = [(MIN_YEAR, DAYS_1900), *zip(range(MIN_YEAR + 1, MAX_YEAR + 1), hko_years)]
    source = render_source(years)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as output:
        output.write(source)
    print(f"Generated {OUTPUT} with {len(years)} years and {len(years) * TERMS_PER_YEAR} dates.")


if __name__ == "__main__":
    main()
