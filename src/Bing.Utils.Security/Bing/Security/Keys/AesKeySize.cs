namespace Bing.Security.Keys;

/// <summary>
/// 表示支持的 AES 密钥位长度。
/// </summary>
public enum AesKeySize
{
    /// <summary>
    /// 128 位 AES 密钥。
    /// </summary>
    Size128 = 128,

    /// <summary>
    /// 192 位 AES 密钥。
    /// </summary>
    Size192 = 192,

    /// <summary>
    /// 256 位 AES 密钥。
    /// </summary>
    Size256 = 256
}